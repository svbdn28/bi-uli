def norm(s):
    s = re.sub("–(?=[A-Za-z])", "-", s)          # en-dash command options
    s = s.replace("‘", "'").replace("’", "'") if re.match(r"^(egrep|grep|echo|tar|test)\b", s) else s
    return s


raw = json.load(open(RAW))
out = []
for i, q in enumerate(raw, 1):
    d = D[i]
    ncorrect = sum(o["correct"] for o in q["options"])
    texts = [o["text"] for o in q["options"]]
    hint = " ".join(q["hint"])
    if "True or False" in hint:
        kind = "truefalse"
    elif ncorrect > 1:
        kind = "multi"
    else:
        kind = "single"
    m = re.search(r"choose (\w+)", hint)
    if m:
        want = {"two": 2, "three": 3}[m.group(1)]
        assert want == ncorrect, (i, want, ncorrect)
    opts = []
    for j, o in enumerate(q["options"]):
        oo = {"text": norm(o["text"]), "correct": o["correct"]}
        if j in d.get("n", {}):
            assert not o["correct"], (i, j)
            oo["note"] = d["n"][j]
        opts.append(oo)
    item = {"id": i, "topic": d["t"], "kind": kind, "choose": ncorrect,
            "question": norm(q["q"]), "questionSk": d["sk"], "options": opts,
            "explanation": d["ex"]}
    if d.get("hk"): item["hook"] = d["hk"]
    if d.get("dm"): item["demo"] = d["dm"]
    item["source"] = d.get("src", "ok")
    out.append(item)

json.dump(out, open(OUT, "w"), ensure_ascii=False, indent=2)
open(OUT, "a").write("\n")
print("written", len(out))
